"""Mengubah isi website menjadi HTML base"""

# establish connection
resp = requests.get(URL)

# membuat object untuk scraping
soup = BeautifulSoup(resp.text, "html.parser")

soup

"""Mengekstrak data Quotes, Author dan Tag, dari semua halaman"""

# list untuk menyimpan semua data hasil ekstraksi
full_data = []

for page in tqdm(range(1, 11)):
  resp = requests.get(f'https://quotes.toscrape.com/page/{page}')

  soup = BeautifulSoup(resp.text, 'html.parser')

  # get all data based on html tags
  raw_data = soup.find_all('div', class_='quote')

  # perulangan untuk mengambil data yg dibutuhkan
  for data in raw_data:
    # only extract the text
    quotes = data.find("span").text

    # extract author
    author = data.find('small').text

    # get tags
    tags = data.find_all('a', class_='tag')

    # create empty list for store all tag value
    get_tag = []

    for tag in tags:
      get_tag.append(tag.text)

    data = {
        'quote':quotes,
        'author':author,
        'tag':get_tag
    }

    full_data.append(data)

  full_data

"""Mengubah data yang sudah discraping menjadi DataFrame"""

quote_data = pd.DataFrame(full_data)

quote_data

"""Menyimpan data menjadi csv"""

# export to csv
quote_data.to_csv('quotes_scrape_data.csv', index = False)

