import requests
from bs4 import BeautifulSoup
from tqdm import tqdm
import pandas as pd

"""Membuat Koneksi pada Website yang akan discraping"""

# set Url
URL = "https://quotes.toscrape.com/"

# get connection
resp = requests.get(URL)

# check status code
